def font(size: int, bold: bool = False) -> ImageFont.FreeTypeFont:
    candidates = [
        "C:/Windows/Fonts/segoeuib.ttf" if bold else "C:/Windows/Fonts/segoeui.ttf",
        "C:/Windows/Fonts/arialbd.ttf" if bold else "C:/Windows/Fonts/arial.ttf",
    ]
    for candidate in candidates:
        if Path(candidate).exists():
            return ImageFont.truetype(candidate, size)
    return ImageFont.load_default()


def text(draw: ImageDraw.ImageDraw, xy, value: str, size: int, fill=TEXT, bold: bool = False, anchor=None) -> None:
    draw.text(xy, value, font=font(size, bold), fill=fill, anchor=anchor)


def wrap(draw: ImageDraw.ImageDraw, value: str, size: int, max_width: int, bold: bool = False) -> list[str]:
    words = value.split()
    lines: list[str] = []
    current = ""
    fnt = font(size, bold)
    for word in words:
        candidate = word if not current else f"{current} {word}"
        if draw.textbbox((0, 0), candidate, font=fnt)[2] <= max_width:
            current = candidate
        else:
            if current:
                lines.append(current)
            current = word
    if current:
        lines.append(current)
    return lines


def paragraph(draw: ImageDraw.ImageDraw, xy, value: str, size: int, max_width: int, fill=MUTED, bold: bool = False, gap: int = 10) -> int:
    x, y = xy
    for line in wrap(draw, value, size, max_width, bold):
        text(draw, (x, y), line, size, fill, bold)
        y += size + gap
    return y


def rounded(draw: ImageDraw.ImageDraw, box, radius: int, fill, outline=None, width: int = 1) -> None:
    draw.rounded_rectangle(box, radius=radius, fill=fill, outline=outline, width=width)


def fit(path: Path, size: tuple[int, int]) -> Image.Image:
    return ImageOps.fit(Image.open(path).convert("RGB"), size, method=Image.Resampling.LANCZOS, centering=(0.5, 0.5))


def contain(path: Path, size: tuple[int, int], color=BG) -> Image.Image:
    return ImageOps.contain(Image.open(path).convert("RGB"), size, method=Image.Resampling.LANCZOS)


def overlay_gradient(img: Image.Image, left_alpha: int = 205, right_alpha: int = 30) -> Image.Image:
    w, h = img.size
    gradient = Image.new("L", (w, 1))
    pixels = gradient.load()
    for x in range(w):
        t = x / max(1, w - 1)
        pixels[x, 0] = round(left_alpha * (1 - t) + right_alpha * t)
    gradient = gradient.resize((w, h))
    layer = Image.new("RGBA", (w, h), (*BG, 255))
    layer.putalpha(gradient)
    return Image.alpha_composite(img.convert("RGBA"), layer)


def add_vignette(img: Image.Image, strength: int = 120) -> Image.Image:
    w, h = img.size
    mask = Image.new("L", (w, h), 0)
    d = ImageDraw.Draw(mask)
    d.ellipse((-w // 5, -h // 2, w + w // 5, h + h // 2), fill=255)
    mask = ImageOps.invert(mask.filter(ImageFilter.GaussianBlur(w // 5)))
    shade = Image.new("RGBA", (w, h), (0, 0, 0, strength))
    shade.putalpha(mask)
    return Image.alpha_composite(img.convert("RGBA"), shade)


def icon_canvas(size: int, safe: float = 0.0, rgb: bool = False) -> Image.Image:
    src = Image.open(SRC_ICON).convert("RGB")
    # Keep the icon generated by imagegen intact, but add safe padding for launcher masks.
    if safe:
        inner = round(size * (1 - safe * 2))
        icon = ImageOps.contain(src, (inner, inner), Image.Resampling.LANCZOS)
        bg = fit(SRC_ICON, (size, size)).filter(ImageFilter.GaussianBlur(max(2, size // 28)))
        bg = Image.blend(Image.new("RGB", (size, size), BG), bg, 0.42)
        x = (size - icon.width) // 2
        y = (size - icon.height) // 2
        bg.paste(icon, (x, y))
        out = bg
    else:
        out = ImageOps.fit(src, (size, size), method=Image.Resampling.LANCZOS)
    return out.convert("RGB" if rgb else "RGBA")


def icon_cutout(size: int, safe: float = 0.0, rgb: bool = False) -> Image.Image:
    """Remove only the edge-connected black background from the imagegen icon."""
    src = ImageOps.fit(Image.open(SRC_ICON).convert("RGB"), (size, size), method=Image.Resampling.LANCZOS)
    if safe:
        inner = round(size * (1 - safe * 2))
        resized = ImageOps.contain(src, (inner, inner), Image.Resampling.LANCZOS)
        canvas = Image.new("RGB", (size, size), BG)
        canvas.paste(resized, ((size - resized.width) // 2, (size - resized.height) // 2))
        src = canvas

    w, h = src.size
    pixels = src.load()

    # Build a conservative candidate map for the outer black background.
    # The dark rounded tile inside the icon is protected because it is not
    # connected to the image edge through similarly dark pixels once the border
    # and highlights are reached.
    candidates = bytearray(w * h)
    for y in range(h):
        for x in range(w):
            r, g, b = pixels[x, y]
            lum = 0.2126 * r + 0.7152 * g + 0.0722 * b
            chroma = max(r, g, b) - min(r, g, b)
            cyan_bias = b - r
            if lum < 34 and chroma < 18 and cyan_bias < 16:
                candidates[y * w + x] = 1

    from collections import deque

    visited = bytearray(w * h)
    q: deque[tuple[int, int]] = deque()
    for x in range(w):
        for y in (0, h - 1):
            idx = y * w + x
            if candidates[idx] and not visited[idx]:
                visited[idx] = 1
                q.append((x, y))
    for y in range(h):
        for x in (0, w - 1):
            idx = y * w + x
            if candidates[idx] and not visited[idx]:
                visited[idx] = 1
                q.append((x, y))

    while q:
        x, y = q.popleft()
        for nx, ny in ((x + 1, y), (x - 1, y), (x, y + 1), (x, y - 1)):
            if 0 <= nx < w and 0 <= ny < h:
                idx = ny * w + nx
                if candidates[idx] and not visited[idx]:
                    visited[idx] = 1
                    q.append((nx, ny))

    bg_mask = Image.frombytes("L", (w, h), bytes(255 if v else 0 for v in visited))
    bg_mask = bg_mask.filter(ImageFilter.GaussianBlur(max(0.35, size / 900)))

    alpha = ImageOps.invert(bg_mask.point(lambda p: 255 if p > 4 else 0))
    alpha = alpha.filter(ImageFilter.GaussianBlur(max(0.25, size / 1600)))

    # Preserve the inner rounded workout-card shape, which is intentionally
    # dark and should remain part of the icon after the outside background goes
    # transparent.
    card_mask = Image.new("L", (w, h), 0)
    cd = ImageDraw.Draw(card_mask)
    cd.rounded_rectangle(
        (
            round(w * 0.188),
            round(h * 0.142),
            round(w * 0.814),
            round(h * 0.850),
        ),
        radius=round(w * 0.082),
        fill=255,
    )
    alpha = Image.composite(Image.new("L", (w, h), 255), alpha, card_mask)

    out = src.convert("RGBA")
    out.putalpha(alpha)
    if rgb:
        matte = Image.new("RGB", (size, size), BG)
        matte.paste(out, mask=out.getchannel("A"))
        return matte
    return out


