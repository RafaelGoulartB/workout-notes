def phone_shell(base: Image.Image, x: int, y: int, w: int, h: int, screen: Image.Image) -> None:
    shadow = Image.new("RGBA", base.size, (0, 0, 0, 0))
    sd = ImageDraw.Draw(shadow)
    rounded(sd, (x - 18, y - 18, x + w + 18, y + h + 18), 52, (0, 0, 0, 120))
    shadow = shadow.filter(ImageFilter.GaussianBlur(24))
    base.alpha_composite(shadow)
    d = ImageDraw.Draw(base)
    rounded(d, (x, y, x + w, y + h), 48, (12, 17, 19, 255), (55, 67, 73, 255), 2)
    rounded(d, (x + 14, y + 14, x + w - 14, y + h - 14), 36, (7, 12, 14, 255))
    screen = ImageOps.fit(screen.convert("RGB"), (w - 28, h - 28), Image.Resampling.LANCZOS)
    mask = Image.new("L", screen.size, 0)
    md = ImageDraw.Draw(mask)
    md.rounded_rectangle((0, 0, screen.width, screen.height), radius=34, fill=255)
    base.paste(screen, (x + 14, y + 14), mask)


