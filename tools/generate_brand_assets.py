def launch_image(size: int) -> Image.Image:
    img = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    icon = icon_cutout(round(size * 0.72), safe=0.02)
    glow = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    gd = ImageDraw.Draw(glow)
    pad = round(size * 0.12)
    gd.ellipse((pad, pad, size - pad, size - pad), fill=(*CYAN, 42))
    glow = glow.filter(ImageFilter.GaussianBlur(max(8, size // 16)))
    img.alpha_composite(glow)
    img.alpha_composite(icon, ((size - icon.width) // 2, (size - icon.height) // 2))
    return img


