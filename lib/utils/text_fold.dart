/// Lowercases [input] and strips Latin diacritics (`Ação` → `acao`), so a
/// search for "acao" finds "ação" and vice versa. Used for the folded
/// `search_text` columns of the AI chat tables and for the query itself.
String foldForSearch(String input) {
  final lower = input.toLowerCase();
  final buffer = StringBuffer();
  for (final rune in lower.runes) {
    final char = String.fromCharCode(rune);
    buffer.write(_fold[char] ?? char);
  }
  return buffer.toString();
}

